"""Financial metric catalog: XBRL concept mapping + label patterns used by deterministic extraction."""
from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class MetricDef:
    key: str
    label: str
    statement: str                 # income | balance | cashflow
    period_type: str               # duration | instant
    concepts: tuple[str, ...]      # us-gaap concepts in priority order
    labels: tuple[str, ...]        # regexes, in priority order (matched against lower-cased row label)
    exclude: tuple[str, ...] = ()  # label regexes to reject
    outflow: bool = False          # reported as a cash outflow; stored as positive payment amount
    mandatory: bool = True         # missing => mandatory evidence missing
    nonnegative: bool = True       # a negative value is an "unexpected sign"
    extra: dict = field(default_factory=dict)


