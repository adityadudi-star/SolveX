"""Hybrid financial metric extraction.

1. Deterministic HTML/inline-XBRL extraction of primary statement rows.
2. Financial concept mapping (catalog).
3. Optional LLM *row selection* only for metrics that deterministic rules could not find
   (the number itself is always read from the filing cell, never generated by the LLM).
4. Evidence verification against the parsed document.
"""
from __future__ import annotations

import re
from dataclasses import asdict, dataclass, field
from datetime import date
from typing import Any, Callable

from app.services.filing_parser import ParsedFiling, Row, Table, parse_display_number, snippet_for_row
from app.utils.catalog import METRICS, STATEMENT_TITLES, MetricDef


@dataclass
class Candidate:
    metric_key: str
    found: bool
    value: float | None = None
    raw_text: str | None = None
    scale: int | None = None
    currency: str | None = None
    unit: str | None = None
    period_start: date | None = None
    period_end: date | None = None
    period_type: str | None = None
    concept: str | None = None
    concept_source: str | None = None      # ix_tag | label_mapping | llm_assisted
    section: str | None = None
    location: str | None = None
    snippet: str | None = None
    method: str | None = None
    table_index: int | None = None
    row_index: int | None = None
    detail: dict[str, Any] = field(default_factory=dict)
    missing_reason: str | None = None


def _currency_from_unit(unit: str | None) -> str | None:
    if not unit:
        return None
    u = unit.lower()
    m = re.search(r"(usd|eur|gbp|jpy|cad|chf|cny|inr|aud|krw|mxn|brl|twd|hkd|sek|nok|dkk|ils)", u)
    return m.group(1).upper() if m else None


def _section_name(table: Table, md: MetricDef) -> str:
    return table.title or STATEMENT_TITLES.get(md.statement, "Financial statement")


def _find_row(md: MetricDef, tables: list[Table]) -> tuple[Table, Row, int] | None:
    pools = sorted([t for t in tables if t.kind == md.statement], key=lambda t: (-t.score, t.index))
    for t in pools[:4]:
        for prio, pat in enumerate(md.labels):
            rx = re.compile(pat)
            for r in t.rows:
                lab = re.sub(r"\s+", " ", r.label.lower()).strip(" :")
                lab = re.sub(r"\s*\(\d\)$", "", lab)  # footnote markers
                if not r.values or not rx.search(lab):
                    continue
                if any(re.search(x, lab) for x in md.exclude):
                    continue
                return t, r, prio
    return None


def _ctx_matches(ctx, md: MetricDef, period_end: date | None) -> bool:
    if ctx is None or ctx.dimensional:
        return False
    if period_end is None:
        return True
    if md.period_type == "instant":
        return ctx.instant and ctx.end == period_end
    return (not ctx.instant) and ctx.end == period_end and ctx.start is not None and 340 <= (ctx.end - ctx.start).days <= 380


def _select_value(md: MetricDef, table: Table, row: Row, parsed: ParsedFiling, period_end: date | None):
    """Return (ValueCell, column_choice, parse_certainty, ctx, notes)."""
    notes: list[str] = []
    # 1) inline XBRL context match
    ix_cells = [v for v in row.values if v.ix is not None]
    if ix_cells:
        for v in ix_cells:
            ctx = parsed.contexts.get(v.ix.context)
            if _ctx_matches(ctx, md, period_end):
                return v, "ix_context", 100, ctx, notes
        notes.append("Inline XBRL facts present but none matched the filing's reporting period.")
    # 2) header years
    vals = row.values
    if table.header_years and period_end:
        years = table.header_years
        if len(years) == len(vals) or len(years) < len(vals):
            idxs = [i for i, y in enumerate(years) if y == period_end.year]
            if idxs and idxs[0] < len(vals):
                return vals[idxs[0]], "header_year", 88, None, notes
        else:
            notes.append(f"Header lists {len(years)} years but row has {len(vals)} values; column alignment uncertain.")
    # 3) positional fallback
    notes.append("Column chosen by position (first value); period could not be confirmed from headers.")
    return vals[0], "positional", 55, None, notes


def _build(md: MetricDef, table: Table, row: Row, prio: int, parsed: ParsedFiling, period_end: date | None,
           filing_url: str, source: str = "label_mapping") -> Candidate:
    cell, col_choice, certainty, ctx, notes = _select_value(md, table, row, parsed, period_end)
    fact = cell.ix
    if fact is not None and col_choice == "ix_context":
        value = fact.value
        scale = fact.scale
        currency = _currency_from_unit(fact.unit)
        concept = fact.name
        concept_source = "ix_tag"
        method = "inline_xbrl_table"
    else:
        scale = table.scale
        value = cell.number * (10 ** (scale or 0))
        currency = "USD" if "$" in row.text else None
        concept = md.concepts[0]
        concept_source = "label_mapping" if source == "label_mapping" else source
        method = "html_table" if source == "label_mapping" else "llm_assisted_row_selection"
        if scale is None:
            notes.append("Table does not state its unit scale (thousands/millions); value taken as displayed.")
    if md.outflow:
        value = abs(value)
    period_start = ctx.start if ctx else None
    pend = ctx.end if ctx else period_end
    unit_txt = None
    if currency:
        unit_txt = f"{currency} ({ {0: 'units', 3: 'thousands', 6: 'millions', 9: 'billions'}.get(scale or 0, '10^' + str(scale)) } as displayed)"
    cand = Candidate(
        metric_key=md.key, found=True, value=value, raw_text=cell.raw, scale=scale, currency=currency, unit=unit_txt,
        period_start=period_start, period_end=pend, period_type=md.period_type, concept=concept, concept_source=concept_source,
        section=_section_name(table, md),
        location=f"{_section_name(table, md)} — table #{table.index}, row {row.index + 1}, column {cell.col + 1}",
        snippet=snippet_for_row(table, row), method=method, table_index=table.index, row_index=row.index,
        detail={"row_label": row.label, "label_priority": prio, "column_choice": col_choice, "parse_certainty": certainty,
                "header_years": table.header_years, "scale_text": table.scale_text, "table_score": table.score,
                "ix_fact": asdict(fact) if fact else None, "notes": notes, "sign_convention": "outflow shown as positive payment" if md.outflow else "as reported",
                "source_url": filing_url},
    )
    return cand


def extract_metrics(parsed: ParsedFiling, period_end: date | None, filing_url: str,
                    llm_row_picker: Callable[[MetricDef, list[tuple[Table, Row]]], tuple[int, int] | None] | None = None) -> list[Candidate]:
    out: list[Candidate] = []
    for md in METRICS:
        hit = _find_row(md, parsed.tables)
        if hit:
            t, r, prio = hit
            out.append(_build(md, t, r, prio, parsed, period_end, filing_url))
            continue
        cand = None
        if llm_row_picker is not None:
            options = _row_options(md, parsed)
            pick = llm_row_picker(md, options) if options else None
            if pick:
                tbl = next((t for t in parsed.tables if t.index == pick[0]), None)
                row = next((r for r in tbl.rows if r.index == pick[1]), None) if tbl else None
                if tbl and row and row.values:
                    cand = _build(md, tbl, row, 99, parsed, period_end, filing_url, source="llm_assisted")
        if cand is None:
            cand = Candidate(metric_key=md.key, found=False, period_type=md.period_type, concept=md.concepts[0],
                             missing_reason=f"No row matching {md.label} was found in the {md.statement} statement of this filing.")
        out.append(cand)
    return out


def _row_options(md: MetricDef, parsed: ParsedFiling, limit: int = 6) -> list[tuple[Table, Row]]:
    words = [w for w in re.split(r"\W+", md.label.lower()) if len(w) > 3]
    opts: list[tuple[int, Table, Row]] = []
    for t in parsed.tables:
        if t.kind != md.statement:
            continue
        for r in t.rows:
            if not r.values:
                continue
            score = sum(w in r.label.lower() for w in words)
            if score:
                opts.append((score, t, r))
    opts.sort(key=lambda x: (-x[0], x[1].index, x[2].index))
    return [(t, r) for _, t, r in opts[:limit]]


def verify_evidence(c: Candidate, parsed: ParsedFiling) -> tuple[bool, list[str]]:
    """Re-locate the evidence in the parsed filing and re-derive the value from the cited cell."""
    notes: list[str] = []
    if not c.found:
        return False, ["metric not found"]
    tbl = next((t for t in parsed.tables if t.index == c.table_index), None)
    row = next((r for r in tbl.rows if r.index == c.row_index), None) if tbl else None
    if not tbl or not row:
        return False, ["cited table/row not present in the parsed filing"]
    if c.raw_text not in row.text:
        notes.append("raw cell text not found in the cited row")
        return False, notes
    parsed_num = parse_display_number(c.raw_text or "")
    if parsed_num is None:
        return False, ["raw cell text is not a number"]
    exp = abs(parsed_num[0]) * (10 ** (c.scale or 0))
    ok = abs(abs(c.value or 0) - exp) <= max(1.0, exp * 1e-9)
    if not ok:
        notes.append("value does not equal raw cell text × scale")
    if not (c.snippet and c.location and c.detail.get("source_url")):
        ok = False
        notes.append("evidence record incomplete (snippet/location/url)")
    return ok, notes
